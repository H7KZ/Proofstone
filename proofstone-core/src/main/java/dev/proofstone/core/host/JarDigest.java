package dev.proofstone.core.host;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HexFormat;
import java.util.List;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

/**
 * The pin of a BuildTools jar (T-M5-05). A BuildTools jar is not byte-reproducible: Maven writes the build time into
 * {@code META-INF/maven/.../pom.properties} ("#Sun Nov 08 17:38:31 UTC 2026"), so two builds of the same source differ
 * in that one entry and nowhere else (checked on spigot 1.8.8: 11961 entries, one differs). The digest covers every
 * entry name and every entry's content, with that Maven date comment line removed. A changed class, resource or entry
 * changes it, so the pin stays strict. Compression, entry times and the date comment do not.
 */
final class JarDigest {

    private JarDigest() {
    }

    static String of(Path jar) {
        MessageDigest digest = newDigest();
        try (ZipFile zip = new ZipFile(jar.toFile())) {
            List<ZipEntry> entries = new ArrayList<>(zip.stream().toList());
            entries.sort(Comparator.comparing(ZipEntry::getName));
            for (ZipEntry entry : entries) {
                byte[] content = entry.isDirectory() ? new byte[0] : read(zip, entry);
                if (entry.getName().endsWith("/pom.properties")) {
                    content = withoutDateComment(content);
                }
                digest.update(entry.getName().getBytes(StandardCharsets.UTF_8));
                digest.update((byte) 0);
                digest.update(newDigest().digest(content));
            }
        } catch (IOException e) {
            throw new UncheckedIOException("cannot digest " + jar, e);
        }
        return HexFormat.of().formatHex(digest.digest());
    }

    /** Drops the {@code #<date>} line that Maven writes at build time; the {@code #Generated by Maven} line stays. */
    static byte[] withoutDateComment(byte[] properties) {
        StringBuilder kept = new StringBuilder();
        for (String line : new String(properties, StandardCharsets.ISO_8859_1).split("\n", -1)) {
            if (!line.startsWith("#") || line.startsWith("#Generated by")) {
                kept.append(line).append('\n');
            }
        }
        return kept.toString().getBytes(StandardCharsets.ISO_8859_1);
    }

    private static byte[] read(ZipFile zip, ZipEntry entry) throws IOException {
        try (InputStream in = zip.getInputStream(entry)) {
            return in.readAllBytes();
        }
    }

    private static MessageDigest newDigest() {
        try {
            return MessageDigest.getInstance("SHA-256");
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-256 is missing from this JVM", e);
        }
    }
}
