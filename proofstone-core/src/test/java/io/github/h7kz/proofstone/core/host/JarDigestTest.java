package io.github.h7kz.proofstone.core.host;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class JarDigestTest {

    private static final String DATE_A = "Sun Nov 08 17:38:31 UTC 2026";
    private static final String DATE_B = "Sun Nov 08 17:38:34 UTC 2026";

    @TempDir
    Path dir;

    private Path jar(String name, String date, String clazz) throws IOException {
        Path jar = dir.resolve(name);
        try (OutputStream out = Files.newOutputStream(jar); ZipOutputStream zip = new ZipOutputStream(out)) {
            put(zip, "META-INF/maven/org.spigotmc/spigot/pom.properties",
                    "#Generated by Maven\n#" + date + "\nversion=1.8.8-R0.1-SNAPSHOT\n");
            put(zip, "org/bukkit/Bukkit.class", clazz);
        }
        return jar;
    }

    private static void put(ZipOutputStream zip, String name, String content) throws IOException {
        zip.putNextEntry(new ZipEntry(name));
        zip.write(content.getBytes(StandardCharsets.UTF_8));
        zip.closeEntry();
    }

    @Test
    void buildTimeInPomPropertiesDoesNotChangeTheDigest() throws IOException {
        Path a = jar("a.jar", DATE_A, "class");
        Path b = jar("b.jar", DATE_B, "class");
        assertNotEquals(-1L, Files.mismatch(a, b), "the raw bytes differ, that is the premise");
        assertEquals(JarDigest.of(a), JarDigest.of(b));
    }

    @Test
    void aChangedClassChangesTheDigest() throws IOException {
        assertNotEquals(JarDigest.of(jar("a.jar", DATE_A, "class one")), JarDigest.of(jar("b.jar", DATE_A, "class two")));
    }

    @Test
    void matchingPinKeepsTheJar() throws IOException {
        Path built = jar("ok.jar", DATE_A, "class");
        SpigotServerJar.requireMatch(built, JarDigest.of(built), "1.8.8");
        assertTrue(Files.exists(built));
    }

    @Test
    void mismatchFailsLoudlyAndRemovesThePartialJar() throws IOException {
        Path built = jar("bad.jar", DATE_A, "class");
        String pin = "0".repeat(64);
        PaperHostException e = assertThrows(PaperHostException.class, () -> SpigotServerJar.requireMatch(built, pin, "1.8.8"));
        assertTrue(e.getMessage().contains("pins " + pin), e.getMessage());
        assertFalse(Files.exists(built), "the .jar.part must not stay in the cache");
    }
}
